const byZone = new Map(PLACES.map((p) => [p.tz, p]));
// Zone names that moved, or that browsers still report under old spellings.
const ALIASES = {
  'Asia/Saigon': 'Asia/Ho_Chi_Minh', 'Europe/Kiev': 'Europe/Kyiv',
  'America/Godthab': 'America/Nuuk', 'Asia/Katmandu': 'Asia/Kathmandu', 'Asia/Rangoon': 'Asia/Yangon',
  'America/Buenos_Aires': 'America/Argentina/Buenos_Aires', 'US/Pacific': 'America/Los_Angeles',
  'US/Eastern': 'America/New_York', 'US/Central': 'America/Chicago', 'US/Mountain': 'America/Denver',
  'Etc/UTC': 'Europe/London', UTC: 'Europe/London', GMT: 'Europe/London',
};

/**
 * Best guess at where someone is from just their time zone. Exact zone match first; otherwise the place whose
 * zone currently has the same UTC offset and is nearest to the zone's own "Region/" prefix; otherwise a point on
 * the equator at offset × 15°. `offsetOf(tz)` is injected so this file stays free of Intl calls in Node tests.
 */
export function guessPlace(tz, offsetOf) {
  const exact = byZone.get(tz) || byZone.get(ALIASES[tz]);
  if (exact) return { ...exact, approx: true };
  const off = offsetOf ? offsetOf(tz) : null;
  if (off !== null && off !== undefined) {
    const region = String(tz).split('/')[0];
    const same = PLACES.filter((p) => offsetOf(p.tz) === off);
    const pick = same.find((p) => p.tz.startsWith(region + '/')) || same[0];
    if (pick) return { ...pick, approx: true };
    return { tz, city: '', country: '', lat: 15, lon: Math.max(-180, Math.min(180, off * 15)), w: 0, approx: true };
  }
  return { tz, city: '', country: '', lat: 15, lon: 0, w: 0, approx: true };
}
